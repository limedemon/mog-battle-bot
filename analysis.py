"""Разбор текста сообщения: культурность (маты и оскорбления) и грамотность.

Всё считается по одному проходу — обработчик дёргается на каждое сообщение чата,
поэтому здесь нет ни регулярок с backtracking, ни обращений к базе.
"""
from __future__ import annotations

import re

# Латиница и цифры, которыми маскируют маты: «сykа», «п1зд», «х*й».
LOOKALIKE = str.maketrans({
    "a": "а", "b": "в", "c": "с", "e": "е", "h": "н", "k": "к", "m": "м", "o": "о",
    "p": "р", "t": "т", "x": "х", "y": "у", "u": "у", "i": "и", "n": "н", "g": "г",
    "3": "е", "0": "о", "4": "ч", "6": "б", "1": "и", "@": "а", "$": "с", "ё": "е",
})

# Символы-разделители внутри слова («х.у.й», «б_л_я») выкидываем.
_JUNK = re.compile(r"[*_'`.,+^~|/\-]")
_WORD = re.compile(r"[a-zа-я0-9@$*_'`.\-]+")
_REPEAT = re.compile(r"(.)\1+")

# Обсценная лексика: снижает культурность с весом 1.
OBSCENE = (
    "хуй", "хуе", "хуё", "хуя", "хую", "хуи", "нахуй", "похуй", "охуе", "ахуе", "хуяр",
    "пизд", "бля", "блят", "бляд", "еба", "ебу", "ебл", "ебн", "ебё", "ебё", "ёб", "ебан",
    "заеб", "наеб", "уеб", "съеб", "отъеб", "въеб", "доеб", "выеб", "переёб",
    "сука", "суки", "суке", "сукой", "сучк", "суче", "залуп", "дроч", "говн", "срак",
    "нахер", "похер", "херн", "хреновин", "пиздец", "манда", "елда",
    "blyat", "blyad", "suka", "pizdec", "hui", "huy", "nahui", "ebat", "ebal",
)

# Адресные оскорбления: вес 2 — это уже не мат в воздух, а токсичность к людям.
INSULTS = (
    "пидор", "пидар", "пидр", "дебил", "даун", "идиот", "тварь", "урод", "мраз", "чмо",
    "мудак", "мудил", "мудоз", "ублюд", "придур", "тупиц", "тупой", "кретин", "шлюх",
    "гандон", "долбоеб", "долбаеб", "долбоёб", "скотин", "шваль", "гнида", "выродок",
    "дегенерат", "имбецил", "ничтожеств", "лох", "уебок", "уёбок", "педик",
    "idiot", "debil", "pidor", "loh", "mraz",
)

# Слова, которые ловятся корнями выше, но матом не являются.
INNOCENT = (
    "требов", "требу", "хуже", "лохмат", "лохан", "лохмот", "молох", "бляха", "херсон",
    "сукно", "суконн", "дауншифт", "даунло", "тварог", "скипид", "мудр", "потреб",
    "хребет", "хребт", "ебей", "ebay",
)

# Сленг, который бьёт по грамотности.
SLANG = {
    "щас", "ща", "крч", "ниче", "нече", "че", "чё", "чо", "шо", "скок", "оч", "нез",
    "спс", "пжлст", "пжл", "кмк", "збс", "тя", "тб", "мб", "типо", "ток", "тока",
    "пасиб", "сяб", "дароу", "здаров", "здрасте", "нз", "кст", "хз", "плз", "плиз",
    "нуб", "имхо", "лан", "ладн", "сорян", "прив", "дратути", "канеш", "конешн",
}

_END = ".!?…)"


def _normalize(word: str) -> str:
    word = _JUNK.sub("", word.lower()).translate(LOOKALIKE)
    return _REPEAT.sub(r"\1", word)


def _is_dirty(word: str) -> tuple[int, int]:
    """Возвращает (маты, оскорбления) для одного нормализованного слова."""
    if len(word) < 3 or any(good in word for good in INNOCENT):
        return 0, 0
    if any(root in word for root in INSULTS):
        return 0, 1
    if any(root in word for root in OBSCENE):
        return 1, 0
    return 0, 0


def literacy(text: str, words: list[str]) -> float | None:
    """Оценка грамотности одного сообщения, 0..1.

    Короткие реплики не оцениваем: «ок» и «+» ничего не говорят о человеке,
    а в среднем они бы утопили любого нормального собеседника.
    """
    letters = [c for c in text if c.isalpha()]
    if len(words) < 4 or len(letters) < 15:
        return None

    score = 1.0
    upper = sum(1 for c in letters if c.isupper())
    if upper / len(letters) > 0.7:
        score -= 0.35
    if not text.strip()[:1].isupper():
        score -= 0.15
    if text.strip()[-1:] not in _END:
        score -= 0.15
    if re.search(r"([а-яa-z])\1{3,}", text.lower()):
        score -= 0.15

    slang = sum(1 for word in words if word in SLANG)
    score -= min(0.3, slang * 0.1)
    return max(0.0, score)


def analyse(text: str) -> dict:
    """Разбор сообщения: сколько матов, оскорблений и какая грамотность."""
    raw = _WORD.findall(text.lower())
    words = [_normalize(word) for word in raw]
    obscene = insults = 0
    for word in words:
        add_obscene, add_insult = _is_dirty(word)
        obscene += add_obscene
        insults += add_insult
    return {
        "words": len(raw),
        "obscene": obscene,
        "insults": insults,
        "dirty": 1 if (obscene or insults) else 0,
        "literacy": literacy(text, words),
    }
